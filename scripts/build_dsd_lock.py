#!/usr/bin/env python3
"""Build a standalone Cargo.lock for dsd-live from the known-good romacode lock.

The sandbox's cargo 1.100 cannot re-resolve the registry (its own HTTP client
is blocked and its cached-index resolution hits an internal bug), so we give
cargo an authoritative lock: closure of {tokio, tokio-rustls, rustls} with
checksums copied verbatim, filtered to packages that exist. cargo --offline
then never consults the index and pulls .crates from the local registry cache.
"""
import hashlib
import os
import re
import sys

SRC_LOCK = "/home/z/my-project/work/romacode/romacode/Cargo.lock"
OUT_LOCK = "/home/z/my-project/work/dsd-live/Cargo.lock"
CACHE = "/home/z/my-project/.cargo-home/registry/cache/index.crates.io-1949cf8c6b5b557f"

text = open(SRC_LOCK).read()

# parse [[package]] blocks
blocks = []
for chunk in re.split(r"\n\[\[package\]\]\n", text)[1:]:
    name = ver = src = cksum = None
    deps = []
    for line in chunk.splitlines():
        if line.startswith("["):  # next section (e.g. [metadata]) — stop
            break
        m = re.match(r'name = "(.*)"$', line)
        if m:
            name = m.group(1)
            continue
        m = re.match(r'version = "(.*)"$', line)
        if m:
            ver = m.group(1)
            continue
        m = re.match(r'source = "(.*)"$', line)
        if m:
            src = m.group(1)
            continue
        m = re.match(r'checksum = "(.*)"$', line)
        if m:
            cksum = m.group(1)
            continue
        m = re.match(r'^\s*"(.*)",?$', line)
        if m:
            deps.append(m.group(1))
    blocks.append({"name": name, "version": ver, "source": src,
                   "checksum": cksum, "deps": deps})

by_key = {}
for b in blocks:
    by_key.setdefault((b["name"], b["version"]), b)

ROOTS = [("tokio", None), ("tokio-rustls", None), ("rustls", None)]
tokio_versions = sorted({v for (n, v) in by_key if n == "tokio"})
print("tokio versions in source lock:", tokio_versions)

def resolve(root_name):
    cands = [(n, v) for (n, v) in by_key if n == root_name]
    if len(cands) == 1:
        return cands[0]
    raise SystemExit(f"root {root_name}: {cands} — pin explicitly")

roots = []
for rn, rv in ROOTS:
    key = (rn, rv) if rv else resolve(rn)
    roots.append(key)

keep = {}
stack = list(roots)
while stack:
    key = stack.pop()
    if key in keep:
        continue
    b = by_key.get(key)
    if b is None:
        print(f"WARN: {key} not in source lock")
        continue
    keep[key] = b
    for d in b["deps"]:
        parts = d.split()
        dname = parts[0]
        # resolve the dep to an exact key: version given in the dep string,
        # or the unique version of that name in the whole source lock
        if len(parts) > 1:
            cands = [(n, v) for (n, v) in by_key if n == dname and v == parts[1]]
        else:
            cands = [(n, v) for (n, v) in by_key if n == dname]
        if len(cands) == 1:
            stack.append(cands[0])
        elif len(cands) > 1:
            # multiple versions — include ALL (target-specific variants)
            for c in cands:
                stack.append(c)

print(f"closure size: {len(keep)}")
missing_cache = []
for (n, v), b in sorted(keep.items()):
    f = os.path.join(CACHE, f"{n}-{v}.crate")
    if os.path.exists(f):
        # verify cached .crate matches the lock checksum (sha256)
        h = hashlib.sha256(open(f, "rb").read()).hexdigest()
        if b["checksum"] and h != b["checksum"]:
            print(f"MISMATCH checksum {n} {v}: lock={b['checksum'][:12]} file={h[:12]}")
    else:
        missing_cache.append(f"{n}-{v}")

print("missing from cache (fine if never compiled):", ", ".join(missing_cache) or "none")

# write the lock (deps filtered to kept keys; name-only modern format)
out = ["# Generated by scripts/build_dsd_lock.py — authoritative offline lock\n"]
for (n, v) in sorted(keep):
    b = keep[(n, v)]
    out.append("[[package]]")
    out.append(f'name = "{n}"')
    out.append(f'version = "{v}"')
    if b["source"]:
        out.append(f'source = "{b["source"]}"')
    if b["checksum"]:
        out.append(f'checksum = "{b["checksum"]}"')
    kd = []
    for d in b["deps"]:
        parts = d.split()
        dname = parts[0]
        if len(parts) > 1:
            target = (dname, parts[1])
        else:
            cands = [(n2, v2) for (n2, v2) in by_key if n2 == dname]
            target = cands[0] if len(cands) == 1 else None
        if target is not None and target in keep:
            kd.append(d)  # verbatim: keeps "name version" disambiguation
    if kd:
        out.append("dependencies = [")
        for d in sorted(set(kd)):
            out.append(f' "{d}",')
        out.append("]")
    out.append("")

open(OUT_LOCK, "w").write("\n".join(out))
print(f"wrote {OUT_LOCK}")
