//! Model profile library — the official "running rules and setup" for every
//! model RomaCode knows about, one JSON file per model under
//! `crates/shared/modeldata/<provider>/<model>.json`, plus a per-provider
//! `_provider.json` default and a global `_default.json` fallback.
//!
//! What a profile carries (all values are taken from the provider's official
//! documentation or flagged `unverified`):
//!
//! * identity: provider folder, family, display name, wire protocol, status;
//! * limits: context window, max output tokens — the server clamps
//!   `max_tokens` so a request can never exceed the model's output limit;
//! * param rules: which sampling parameters the model accepts and their
//!   legal ranges (reasoning families reject `temperature`/`top_p`; the
//!   Anthropic wire range is 0..=1; some models accept temperature OR
//!   top_p, never both);
//! * wire rules: `max_tokens` vs `max_completion_tokens`, whether `stop`
//!   is accepted;
//! * endpoints, pricing (when officially listed), docs and source URLs.
//!
//! Resolution is deliberately total: [`profile_for`] NEVER fails and NEVER
//! blocks a request. It walks
//! exact → normalized → family (vendor-prefixed aggregator ids) → the
//! provider's `_provider.json` → the global `_default.json`. An unknown
//! model on an unknown host still runs with permissive defaults.
//!
//! The JSON files are embedded at compile time via [`modeldata_gen::SOURCES`]
//! (generated by `scripts/gen_modeldata.py`); nothing is read from disk at
//! runtime, and the TUI reads the same embedded library — one source of
//! truth for both sides, like `catalog`.

/// Generated include_str! table (scripts/gen_modeldata.py). A file-module
/// child would resolve under src/modeldata/, so the path is pinned here.
#[path = "modeldata_gen.rs"]
mod modeldata_gen;

use serde::Deserialize;
use std::collections::HashMap;
use std::sync::OnceLock;

/// Whether one sampling parameter is accepted and its legal range.
#[derive(Clone, Copy, Debug, Deserialize, Default)]
pub struct ParamSpec {
    /// Does the model accept this parameter at all? `false` = the request
    /// must OMIT it (sending it is a 400 on the reasoning families).
    #[serde(default = "default_true")]
    pub supported: bool,
    #[serde(default)]
    pub min: f32,
    #[serde(default)]
    pub max: f32,
}

/// Parameter rules for one model.
#[derive(Clone, Copy, Debug, Deserialize, Default)]
pub struct Params {
    #[serde(default)]
    pub temperature: Option<ParamSpec>,
    #[serde(default)]
    pub top_p: Option<ParamSpec>,
    #[serde(default)]
    pub reasoning_effort: Option<ParamSpec>,
}

/// Capability flags (missing = false; absent data is not invented).
#[derive(Clone, Copy, Debug, Deserialize, Default)]
pub struct Features {
    #[serde(default)]
    pub vision: bool,
    #[serde(default)]
    pub tools: bool,
    #[serde(default)]
    pub json_mode: bool,
    #[serde(default)]
    pub reasoning: bool,
    #[serde(default)]
    pub prefix_caching: bool,
    #[serde(default)]
    pub computer_use: bool,
    #[serde(default)]
    pub web_search: bool,
}

/// Wire-level request rules.
#[derive(Clone, Debug, Deserialize)]
pub struct Wire {
    /// `"max_tokens"`, `"max_completion_tokens"`, or `""` (= decide from the
    /// provider id, the legacy behavior).
    #[serde(default)]
    pub max_tokens_param: String,
    /// Some models accept temperature OR top_p but not both (Anthropic 4.5).
    #[serde(default, rename = "temperature_or_top_p_exclusive")]
    pub temperature_or_top_p_exclusive: bool,
    /// Reasoning models reject `stop`.
    #[serde(default = "default_true")]
    pub stop_supported: bool,
}

impl Default for Wire {
    fn default() -> Self {
        Self {
            max_tokens_param: String::new(),
            temperature_or_top_p_exclusive: false,
            stop_supported: true,
        }
    }
}

/// One model's official running rules.
#[derive(Clone, Debug, Deserialize)]
pub struct ModelProfile {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub provider: String,
    #[serde(default)]
    pub family: String,
    #[serde(default)]
    pub display_name: String,
    /// `openai` or `anthropic` — mirrors `catalog::ApiKind`.
    #[serde(default)]
    pub api: String,
    /// `stable | preview | beta | legacy | provider-default | unknown`.
    #[serde(default)]
    pub status: String,
    /// 0 = unknown (never clamp).
    #[serde(default)]
    pub context_window: u64,
    /// 0 = unknown (never clamp).
    #[serde(default)]
    pub max_output_tokens: u32,
    #[serde(default)]
    pub features: Features,
    #[serde(default)]
    pub params: Params,
    #[serde(default)]
    pub wire: Wire,
    /// Officially listed pricing, when published. Display-only.
    #[serde(default)]
    pub pricing: Option<serde_json::Value>,
    #[serde(default)]
    pub endpoints: serde_json::Value,
    #[serde(default)]
    pub wire_notes: Vec<String>,
    #[serde(default)]
    pub docs: Option<String>,
    #[serde(default)]
    pub sources: Vec<String>,
    /// Fields that could not be verified against official documentation.
    #[serde(default)]
    pub unverified_fields: Vec<String>,
}

fn default_true() -> bool {
    true
}

/// Provider-family routing for aggregator ids: the first path segment maps
/// to the vendor folder whose profiles apply.
fn family_of(first_segment: &str) -> Option<&'static str> {
    match first_segment {
        "anthropic" => Some("anthropic"),
        "openai" => Some("openai"),
        "google" | "gemini" => Some("google"),
        "deepseek" => Some("deepseek"),
        "xai" | "grok" => Some("xai"),
        "zai" | "glm" | "z-ai" => Some("zai"),
        "moonshot" | "kimi" => Some("moonshot"),
        "qwen" | "alibaba" => Some("qwen"),
        "minimax" => Some("minimax"),
        "mistral" => Some("mistral"),
        "cohere" => Some("cohere"),
        "perplexity" => Some("perplexity"),
        "google-vertex" | "amazon-bedrock" => None, // hosted variants, not ids
        _ => None,
    }
}

/// Family routing from the MODEL NAME itself: a model served through an
/// aggregator keeps its vendor identity in the id (`gpt-5.2` on Azure is
/// still an OpenAI model). Conservative prefixes only — anything ambiguous
/// stays with the provider's own defaults.
fn family_from_name(norm: &str) -> Option<&'static str> {
    let starts = |p: &[&str]| p.iter().any(|prefix| norm.starts_with(prefix));
    if starts(&["gpt-", "o1", "o3-", "o4-"]) {
        Some("openai")
    } else if starts(&["claude"]) {
        Some("anthropic")
    } else if starts(&["gemini"]) {
        Some("google")
    } else if starts(&["deepseek"]) {
        Some("deepseek")
    } else if starts(&["grok"]) {
        Some("xai")
    } else if starts(&["glm"]) {
        Some("zai")
    } else if starts(&["kimi"]) {
        Some("moonshot")
    } else if starts(&["qwen"]) {
        Some("qwen")
    } else if starts(&["minimax"]) {
        Some("minimax")
    } else if starts(&["mistral", "codestral", "magistral"]) {
        Some("mistral")
    } else if starts(&["command-"]) {
        Some("cohere")
    } else if starts(&["sonar"]) {
        Some("perplexity")
    } else {
        None
    }
}

/// Normalize a raw model id so tolerant lookup can match it against a
/// profile's canonical id:
///
/// * vendor path prefixes drop (`anthropic/…`, `accounts/fireworks/models/…`);
/// * `:` tags drop (`:latest`, `:free`, `:high`);
/// * `.` and `_` unify to `-` (`claude-sonnet-5.5` == `claude-sonnet-5-5`);
/// * release-date suffixes drop (`claude-sonnet-4-5-20250929`,
///   `gemini-2.5-pro-preview-06-05`).
///
/// Conservative by design: anything it does not recognize stays, and a miss
/// falls through to the provider default — never an error.
pub fn normalize(raw: &str) -> String {
    let s0 = raw.trim();
    // Reserved registry namespace: `_provider` / `_default` are looked up by
    // their literal names, never normalized.
    if s0.starts_with('_') {
        return s0.to_ascii_lowercase();
    }
    let mut s = s0.to_ascii_lowercase();
    // colon tags first (`openai/gpt-5.2:high` → `openai/gpt-5.2`)
    if let Some(pos) = s.find(':') {
        s.truncate(pos);
    }
    // last path segment
    if let Some(pos) = s.rfind('/') {
        s = s[pos + 1..].to_string();
    }
    s = s.replace(['.', '_'], "-");
    // collapse runs of '-' and trim ends
    let mut out = String::with_capacity(s.len());
    let mut prev_dash = false;
    for c in s.chars() {
        if c == '-' {
            if !prev_dash {
                out.push('-');
            }
            prev_dash = true;
        } else {
            out.push(c);
            prev_dash = false;
        }
    }
    let mut out = out.trim_matches('-').to_string();
    // release-date suffixes: `-20250929`, `-2025-12-11`, `-MM-DD` (then any
    // `-preview`), `-latest` — each strip is conservative and exact-length
    let bytes = out.as_bytes();
    let digits = |b: u8| b.is_ascii_digit();
    if out.len() > 9 && bytes[out.len() - 9] == b'-' && bytes[out.len() - 8..].iter().all(|&b| digits(b)) {
        out.truncate(out.len() - 9);
    } else if out.len() > 11
        && bytes[out.len() - 11] == b'-'
        && (0..10).all(|i| i == 4 || i == 7 || digits(bytes[out.len() - 10 + i]))
    {
        out.truncate(out.len() - 11);
    } else if out.len() > 6
        && bytes[out.len() - 6] == b'-'
        && digits(bytes[out.len() - 5])
        && digits(bytes[out.len() - 4])
        && bytes[out.len() - 3] == b'-'
        && digits(bytes[out.len() - 2])
        && digits(bytes[out.len() - 1])
    {
        // `gemini-2.5-pro-preview-06-05` → `gemini-2.5-pro-preview`
        out.truncate(out.len() - 6);
    }
    // preview / latest suffixes
    for suffix in ["-preview", "-latest"] {
        if let Some(stripped) = out.strip_suffix(suffix) {
            out = stripped.to_string();
        }
    }
    let mut out2 = String::with_capacity(out.len());
    let mut prev_dash = false;
    for c in out.chars() {
        if c == '-' {
            if !prev_dash {
                out2.push('-');
            }
            prev_dash = true;
        } else {
            out2.push(c);
            prev_dash = false;
        }
    }
    out2.trim_matches('-').to_string()
}

struct Registry {
    by_key: HashMap<(String, String), usize>,
    all: Vec<ModelProfile>,
}

fn registry() -> &'static Registry {
    static REG: OnceLock<Registry> = OnceLock::new();
    REG.get_or_init(|| {
        let mut all = Vec::new();
        let mut by_key = HashMap::new();
        for (provider, _path) in modeldata_gen::SOURCES {
            // include_str! guarantees presence; parse failure would be a
            // build bug, so a broken file is skipped loudly in tests and
            // quietly (profile falls back) at runtime.
            let Ok(p) = serde_json::from_str::<ModelProfile>(_path) else {
                continue;
            };
            let key = (provider.to_string(), normalize(&p.id));
            by_key.insert(key, all.len());
            all.push(p);
        }
        Registry { by_key, all }
    })
}

/// Exact (provider, model) lookup with normalized ids.
pub fn find(provider: &str, model: &str) -> Option<&'static ModelProfile> {
    let reg = registry();
    let provider = provider.trim().to_ascii_lowercase();
    let norm = normalize(model);
    if norm.is_empty() {
        return None;
    }
    reg.by_key
        .get(&(provider.clone(), norm.clone()))
        .map(|&i| &reg.all[i])
        // vendor-prefixed aggregator id: route to the family folder
        .or_else(|| {
            let first = model.trim().split('/').next().unwrap_or("").to_ascii_lowercase();
            family_of(&first).and_then(|fam| {
                if fam == provider {
                    None
                } else {
                    reg.by_key.get(&(fam.to_string(), norm.clone())).map(|&i| &reg.all[i])
                }
            })
        })
        // no path prefix: route by the model-name shape (gpt-5.2 on Azure,
        // claude-… on a proxy, deepseek-chat on a custom host)
        .or_else(|| {
            family_from_name(&norm).and_then(|fam| {
                if fam == provider {
                    None
                } else {
                    reg.by_key.get(&(fam.to_string(), norm)).map(|&i| &reg.all[i])
                }
            })
        })
}

/// TOTAL resolution: a profile for every (provider, model) pair, always.
///
/// Order: exact/normalized/family match → the provider's `_provider.json`
/// default → the global `_default.json`. Never errors, never blocks: an
/// unknown model keeps running with permissive rules.
pub fn profile_for(provider: &str, model: &str) -> &'static ModelProfile {
    if let Some(p) = find(provider, model) {
        return p;
    }
    let reg = registry();
    let provider = provider.trim().to_ascii_lowercase();
    if let Some(&i) = reg.by_key.get(&(provider, "_provider".to_string())) {
        return &reg.all[i];
    }
    let di = reg
        .by_key
        .get(&("_default".to_string(), "_default".to_string()))
        .expect("global default profile missing from SOURCES");
    &reg.all[*di]
}

/// Every concrete model profile for one provider (sorted by id; no
/// `_provider` entry). Feeds pickers on both sides.
pub fn catalog_for(provider: &str) -> Vec<&'static ModelProfile> {
    let reg = registry();
    let provider = provider.trim().to_ascii_lowercase();
    let mut out: Vec<&ModelProfile> = reg
        .all
        .iter()
        .filter(|p| p.provider == provider && p.id != "_provider")
        .collect();
    out.sort_by(|a, b| a.id.cmp(&b.id));
    out
}

/// Short human-readable line for pickers/status: context, output limit,
/// headline features.
pub fn summary(p: &ModelProfile) -> String {
    let ctx = if p.context_window >= 1_000_000 {
        format!("{}M", p.context_window / 1_000_000)
    } else if p.context_window > 0 {
        format!("{}K", p.context_window / 1_000)
    } else {
        "?".to_string()
    };
    let out = if p.max_output_tokens >= 1_000 {
        format!("{}K", p.max_output_tokens / 1_000)
    } else if p.max_output_tokens > 0 {
        format!("{}", p.max_output_tokens)
    } else {
        "?".to_string()
    };
    let mut feats: Vec<&str> = Vec::new();
    if p.features.vision {
        feats.push("vision");
    }
    if p.features.tools {
        feats.push("tools");
    }
    if p.features.reasoning {
        feats.push("reasoning");
    }
    format!("{ctx} ctx · {out} out{}", if feats.is_empty() {
        String::new()
    } else {
        format!(" · {}", feats.join("+"))
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::catalog;

    #[test]
    fn every_embedded_profile_parses() {
        let reg = registry();
        assert!(reg.all.len() >= 80, "library looks truncated: {}", reg.all.len());
        for p in &reg.all {
            assert!(!p.display_name.is_empty(), "{}: missing display_name", p.id);
            for (i, src) in p.sources.iter().enumerate() {
                assert!(src.starts_with("https://"), "{}: source {i} not a URL", p.id);
            }
        }
    }

    #[test]
    fn keys_are_unique_and_folders_match() {
        let reg = registry();
        let mut seen = std::collections::HashSet::new();
        for p in &reg.all {
            let key = (p.provider.clone(), normalize(&p.id));
            assert!(seen.insert(key.clone()), "duplicate profile {key:?}");
        }
    }

    #[test]
    fn normalize_unifies_known_id_shapes() {
        assert_eq!(normalize("claude-sonnet-5-5"), "claude-sonnet-5-5");
        assert_eq!(normalize("anthropic/claude-sonnet-5.5"), "claude-sonnet-5-5");
        assert_eq!(normalize("claude-sonnet-4-5-20250929"), "claude-sonnet-4-5");
        assert_eq!(normalize("openai/gpt-5.2:high"), "gpt-5-2");
        assert_eq!(normalize("accounts/fireworks/models/llama-v3p3-70b-instruct"), "llama-v3p3-70b-instruct");
        assert_eq!(normalize("gemini-2.5-pro-preview-06-05"), "gemini-2-5-pro");
        assert_eq!(normalize("MiniMax-M3.1-Flash"), "minimax-m3-1-flash");
        assert_eq!(normalize("deepseek-chat"), "deepseek-chat");
        assert_eq!(normalize("meta-llama/Llama-3.3-70B-Instruct-Turbo"), "llama-3-3-70b-instruct-turbo");
    }

    #[test]
    fn family_routing_resolves_vendor_prefixed_ids() {
        let p = find("openrouter", "anthropic/claude-sonnet-5.5").expect("family route");
        assert_eq!(p.provider, "anthropic");
        let d = find("openrouter", "deepseek/deepseek-chat").expect("family route");
        assert_eq!(d.provider, "deepseek");
        // same-provider prefix must not self-route to a wrong folder
        assert!(find("groq", "openai/gpt-oss-120b").is_none());
    }

    #[test]
    fn date_suffixed_snapshot_ids_resolve() {
        let p = find("anthropic", "claude-sonnet-4-5-20250929").expect("snapshot id");
        assert_eq!(p.id, "claude-sonnet-4-5");
    }

    #[test]
    fn profile_for_is_total_and_never_blocks() {
        // the exact report scenario: a model nobody knows, on a host nobody
        // configured — still a profile, still permissive, never an error
        let p = profile_for("some-unknown-host", "totally-made-up-model");
        assert_eq!(p.id, "_default");
        assert!(p.params.temperature.as_ref().map(|t| t.supported).unwrap_or(true));
        // known provider without a model file → provider defaults
        let g = profile_for("google", "brand-new-gemini-something");
        assert_eq!(g.id, "_provider");
        assert_eq!(g.provider, "google");
    }

    #[test]
    fn reasoning_wire_rules_are_explicit() {
        let g = find("openai", "gpt-5.2").expect("gpt-5.2 profile");
        assert_eq!(g.wire.max_tokens_param, "max_completion_tokens");
        assert!(!g.params.temperature.as_ref().expect("temperature spec").supported);
        assert!(!g.wire.stop_supported);
        assert!(g.params.reasoning_effort.as_ref().expect("effort").supported);
    }

    #[test]
    fn anthropic_temperature_range_is_clamped_to_official_bounds() {
        for m in ["claude-sonnet-5-5", "claude-opus-4-5", "claude-3-5-sonnet-20241022"] {
            let p = find("anthropic", m).expect(m);
            let t = p.params.temperature.as_ref().expect("anthropic temperature spec");
            assert!(t.max <= 1.0, "{m}: temperature max {} exceeds the Anthropic 0..=1 range", t.max);
        }
    }

    #[test]
    fn every_known_provider_default_model_resolves() {
        // "must not get stuck due to lack of requirement": resolution must
        // always return a usable profile. The detailed profile library covers
        // the core adapter providers; the long tail of catalog providers has
        // no hand-written profiles and intentionally uses the graceful global
        // fallback (profile_for never errors).
        for k in catalog::known() {
            assert!(!k.default_model.is_empty(), "{}: no default model in catalog", k.id);
            let p = profile_for(k.id.as_str(), k.default_model.as_str());
            assert!(!p.id.is_empty(), "{}: profile resolution returned nothing", k.id);
            let is_core = romacode_providers::catalog::BUILTIN_SNAPSHOT
                .iter()
                .any(|e| e.id.eq_ignore_ascii_case(&k.id));
            if is_core {
                assert_ne!(p.id, "_default", "{}: core default fell through to global default", k.id);
                assert_ne!(p.provider, "_default", "{}: resolved to the unknown-model stub", k.id);
            }
        }
    }

    #[test]
    fn catalog_for_lists_concrete_models_sorted() {
        let a = catalog_for("anthropic");
        assert!(a.len() >= 10, "anthropic folder: {}", a.len());
        assert!(a.iter().all(|p| p.id != "_provider"));
        let mut ids: Vec<&str> = a.iter().map(|p| p.id.as_str()).collect();
        let sorted = ids.clone();
        ids.sort();
        assert_eq!(ids, sorted, "catalog_for must sort");
        assert!(catalog_for("no-such-provider").is_empty());
    }

    #[test]
    fn summaries_are_human_and_safe() {
        let s = summary(find("anthropic", "claude-sonnet-5-5").unwrap());
        assert!(s.contains("1M ctx") && s.contains("128K out"), "{s}");
        let s = summary(&profile_for("ollama", "anything"));
        assert!(s.contains("? ctx"), "unknown limits must render as ?: {s}");
    }
}
