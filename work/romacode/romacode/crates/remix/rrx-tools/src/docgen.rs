//! Doc Generator: markdown docs per contract from the AST + natspec.

use serde_json::Value;

pub fn generate(output: &Value, title: &str) -> String {
    let mut out = format!("# {title}\n\nDocumentation generated by rrx (Doc Generator).\n\n");
    if let Some(sources) = output.get("sources").and_then(|s| s.as_object()) {
        for (file, sv) in sources {
            let Some(ast) = sv.get("ast") else { continue };
            if let Some(contracts) = collect_contracts(ast) {
                for c in contracts {
                    out.push_str(&render_contract(file, &c));
                }
            }
        }
    }
    out
}

fn collect_contracts(node: &Value) -> Option<Vec<Value>> {
    let mut found = vec![];
    walk(node, &mut found);
    if found.is_empty() {
        None
    } else {
        Some(found)
    }
}

fn walk(node: &Value, found: &mut Vec<Value>) {
    match node {
        Value::Object(map) => {
            if map.get("nodeType").and_then(|t| t.as_str()) == Some("ContractDefinition") {
                found.push(node.clone());
                return;
            }
            for v in map.values() {
                walk(v, found);
            }
        }
        Value::Array(arr) => {
            for v in arr {
                walk(v, found);
            }
        }
        _ => {}
    }
}

fn natspec(node: &Value, key: &str) -> String {
    node.get("documentation").and_then(|d| d.get(key))
        .or_else(|| node.get("documentation").and_then(|d| d.get("text")))
        .and_then(|v| v.as_str())
        .unwrap_or("")
        .trim()
        .to_string()
}

fn render_contract(file: &str, c: &Value) -> String {
    let name = c.get("name").and_then(|n| n.as_str()).unwrap_or("?");
    let kind = c.get("contractKind").and_then(|k| k.as_str()).unwrap_or("contract");
    let mut out = format!("## `{name}` ({kind})\n\n");
    out.push_str(&format!("_Source:_ `{file}`\n\n"));
    let notice = natspec(c, "text");
    if !notice.is_empty() {
        out.push_str(&format!("{notice}\n\n"));
    }

    let nodes = c.get("nodes").and_then(|n| n.as_array()).cloned().unwrap_or_default();
    let mut fns = String::from("| function | visibility | mutability | notice |\n|---|---|---|---|\n");
    let mut vars = String::new();
    let mut events = String::new();
    for n in &nodes {
        match n.get("nodeType").and_then(|t| t.as_str()).unwrap_or("") {
            "FunctionDefinition" => {
                let fname = n.get("name").and_then(|f| f.as_str()).unwrap_or("constructor");
                let vis = n.get("visibility").and_then(|v| v.as_str()).unwrap_or("");
                let sm = n.get("stateMutability").and_then(|m| m.as_str()).unwrap_or("");
                let notice = natspec(n, "text").replace('|', "\\|");
                fns.push_str(&format!("| `{fname}` | {vis} | {sm} | {notice} |\n"));
            }
            "VariableDeclaration" => {
                let vn = n.get("name").and_then(|f| f.as_str()).unwrap_or("");
                let vis = n.get("visibility").and_then(|v| v.as_str()).unwrap_or("");
                vars.push_str(&format!("- `{vn}` ({vis})\n"));
            }
            "EventDefinition" => {
                let en = n.get("name").and_then(|f| f.as_str()).unwrap_or("");
                events.push_str(&format!("- `{en}`\n"));
            }
            _ => {}
        }
    }
    if !vars.is_empty() {
        out.push_str("### State variables\n\n");
        out.push_str(&vars);
        out.push('\n');
    }
    if !fns.ends_with("|---|\n") {
        out.push_str("### Functions\n\n");
        out.push_str(&fns);
        out.push('\n');
    }
    if !events.is_empty() {
        out.push_str("### Events\n\n");
        out.push_str(&events);
        out.push('\n');
    }
    out
}
