//! The `Tool` trait — the single contract every tool implements, whether it
//! is built-in, declared, LLM-generated, imported from OpenAPI/MCP/REST/CLI,
//! or composed from other tools.

use crate::error::ToolResult;
use crate::schema::Schema;
use async_trait::async_trait;
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::Arc;

/// Which of the 8 universal tool-source mechanisms produced this tool. This is
/// metadata only — once loaded, every tool is just a `Tool`.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq, Eq)]
#[serde(rename_all = "snake_case")]
pub enum ToolSourceKind {
    /// Shipped with the framework (`builtin`).
    Builtin,
    /// Built from a YAML/JSON declaration (`declarative`).
    Declarative,
    /// Generated by an LLM from a natural-language description (`llm_gen`).
    LlmGenerated,
    /// Imported from an OpenAPI/Swagger spec (`openapi`).
    OpenApi,
    /// Bridged from an MCP server (`mcp`).
    Mcp,
    /// A REST endpoint wrapped as a tool (`rest`).
    Rest,
    /// A GraphQL query wrapped as a tool (`graphql`).
    GraphQL,
    /// A CLI binary wrapped as a tool (`cli`).
    Cli,
    /// Composed from other tools — pipeline/parallel/branch/loop/dag
    /// (`compose`). The inner `&'static str` names the composition kind.
    Compose(&'static str),
    /// Pulled from a marketplace or URL (`marketplace`).
    Marketplace,
}

impl Default for ToolSourceKind {
    fn default() -> Self {
        ToolSourceKind::Builtin
    }
}

impl ToolSourceKind {
    pub fn as_str(&self) -> &'static str {
        match self {
            Self::Builtin => "builtin",
            Self::Declarative => "declarative",
            Self::LlmGenerated => "llm_gen",
            Self::OpenApi => "openapi",
            Self::Mcp => "mcp",
            Self::Rest => "rest",
            Self::GraphQL => "graphql",
            Self::Cli => "cli",
            Self::Compose(_) => "compose",
            Self::Marketplace => "marketplace",
        }
    }
}

/// Per-call execution context: the sandbox in force, a correlation id, and a
/// cancellation flag. Tools that fan out (composition) pass a child context
/// derived from this one — the child shares the parent's *live* cancellation
/// flag (an `Arc<AtomicBool>`), so spawned steps observe a timeout or cancel
/// mid-flight instead of running to completion detached. The Executor
/// populates `allow_net` / `allow_fs_paths` from its
/// [`Sandbox`](crate::sandbox::Sandbox) so tools can self-check I/O policy.
#[derive(Debug, Clone)]
pub struct ToolContext {
    /// A unique id for this invocation, for tracing/monitoring.
    pub correlation_id: String,
    /// Hard wall-clock budget for this single call, in ms. `0` = no limit
    /// (the executor still applies the sandbox timeout).
    pub timeout_ms: u64,
    /// Set to true by a parent to cancel a long-running tool. This is the
    /// spawn-time snapshot; see [`ToolContext::is_cancelled`].
    pub cancelled: bool,
    /// The live, shared cancellation flag. The executor flips this when the
    /// sandbox timeout fires, and composition tools pass clones down to
    /// spawned steps so cancellation propagates. Check it with
    /// [`ToolContext::is_cancelled`].
    pub cancel: Arc<AtomicBool>,
    /// Whether outbound network is permitted in this call.
    pub allow_net: bool,
    /// Filesystem roots the tool may touch. Defaults to the whole
    /// filesystem; an explicitly empty list disables FS access.
    pub allow_fs_paths: Vec<String>,
}

impl Default for ToolContext {
    fn default() -> Self {
        Self {
            correlation_id: "default".to_string(),
            timeout_ms: 0,
            cancelled: false,
            cancel: Arc::new(AtomicBool::new(false)),
            allow_net: true,
            allow_fs_paths: vec!["/".to_string()],
        }
    }
}

impl ToolContext {
    pub fn new(correlation_id: impl Into<String>) -> Self {
        Self {
            correlation_id: correlation_id.into(),
            timeout_ms: 0,
            cancelled: false,
            cancel: Arc::new(AtomicBool::new(false)),
            allow_net: true,
            allow_fs_paths: vec!["/".to_string()],
        }
    }
    pub fn with_timeout(mut self, ms: u64) -> Self {
        self.timeout_ms = ms;
        self
    }
    /// Has this call been cancelled — either the spawn-time snapshot
    /// (`cancelled`) or the live shared flag (`cancel`)? Tools should check
    /// this (not the `cancelled` field) so they observe cancellation that
    /// arrives after they started.
    pub fn is_cancelled(&self) -> bool {
        self.cancelled || self.cancel.load(Ordering::Relaxed)
    }
    /// Mark this call tree as cancelled: every holder of a clone of the
    /// shared flag observes it.
    pub fn cancel(&self) {
        self.cancel.store(true, Ordering::Relaxed);
    }
    /// Check that network is permitted.
    pub fn check_net(&self) -> Result<(), crate::error::ToolError> {
        if self.allow_net {
            Ok(())
        } else {
            Err(crate::error::ToolError::Sandbox(
                "network access is disabled in this context".to_string(),
            ))
        }
    }
    /// Check that `path` is under one of the allowed FS roots (no FS access
    /// when the allow-list is empty). Delegates to
    /// [`path_inside_roots`](crate::sandbox::path_inside_roots), which
    /// normalizes `..`/`.` lexically and fails closed.
    pub fn check_path(&self, path: &str) -> Result<(), crate::error::ToolError> {
        if self.allow_fs_paths.is_empty() {
            return Err(crate::error::ToolError::Sandbox(
                "filesystem access is disabled in this context".to_string(),
            ));
        }
        crate::sandbox::path_inside_roots(path, &self.allow_fs_paths)
    }
}

/// The single trait every tool implements. `execute` is async so tools that
/// do network I/O (REST, web fetch, MCP) can run without blocking the
/// executor's runtime.
#[async_trait]
pub trait Tool: Send + Sync {
    /// Stable, unique, dot-namespaced id, e.g. `math.add`, `web.fetch`,
    /// `compose.pipeline.myflow`. This is the key the registry indexes by.
    fn name(&self) -> &str;

    /// Human-readable summary; shown in `rc list` and `rc info`.
    fn description(&self) -> &str;

    /// The input schema. The validator runs against this before `execute`.
    fn schema(&self) -> Schema;

    /// Which source produced this tool.
    fn source(&self) -> ToolSourceKind;

    /// A category label for grouping (`math`, `web`, `compose`, …). Default
    /// is derived from the name's first segment when not overridden.
    fn category(&self) -> &str {
        // default: first segment of a dot-namespaced name, else "misc"
        self.name().split('.').next().unwrap_or("misc")
    }

    /// The tool's semver version (default `0.1.0`). The lifecycle manager uses
    /// this for upgrade/retire decisions.
    fn version(&self) -> &str {
        "0.1.0"
    }

    /// Run the tool. `input` is a JSON object matching `schema()`. The
    /// executor has already validated it and applied the sandbox.
    async fn execute(&self, input: &Value, ctx: &ToolContext) -> ToolResult<Value>;
}

/// A boxed, shareable tool handle — `Arc<dyn Tool>` is the currency of the
/// registry and the composition layer.
pub type ToolArc = std::sync::Arc<dyn Tool>;

/// Helper: build a [`ToolArc`] from any `Tool`.
pub fn arc<T: Tool + 'static>(t: T) -> ToolArc {
    std::sync::Arc::new(t)
}
